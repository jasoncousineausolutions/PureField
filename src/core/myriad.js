/**
 * Expand runs into a Map(code point → width). A letter with a cedilla or
 * comma below (ş ţ ș ț Ş Ţ Ș Ț ģ ķ ļ ņ ŗ…) is as wide as its base letter in
 * Myriad Pro; pdf.js has no factors for them, so the runs hold Helvetica's
 * widths there (ş 500 for s 396), and Romanian lines measured long and
 * wrapped a word early (anaf-d1000's article 2.5, as Reader prints it).
 */
export function myriadWidths(runs) {
  const m = new Map();
  for (const [first, ...ws] of runs) ws.forEach((w, i) => m.set(first + i, w));
  for (const cp of m.keys()) {
    const d = String.fromCodePoint(cp).normalize('NFD');
    if (d.length === 2 && (d[1] === '\u0327' || d[1] === '\u0326') && m.has(d.codePointAt(0))) m.set(cp, m.get(d.codePointAt(0)));
  }
  return m;
}
